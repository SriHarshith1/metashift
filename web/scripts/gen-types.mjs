// Builds src/types/generated.ts from the JSON schemas that `metashift schema` writes.
import { readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

// Pydantic titles every field ("Patch", "Headline"), which json-schema-to-typescript turns
// into one type alias each. Drop titles on non-object schemas so fields stay inline.
function stripFieldTitles(node) {
  if (Array.isArray(node)) return node.forEach(stripFieldTitles);
  if (node === null || typeof node !== "object") return;
  if (!node.properties && !node.additionalProperties && node.type !== "object") delete node.title;
  Object.values(node).forEach(stripFieldTitles);
}

const names = ["ReportFile", "IndexFile"];
let out = "/* Generated by `npm run gen:types` from pipeline/metashift/core/models.py. Do not edit. */\n\n";
for (const name of names) {
  const schema = JSON.parse(readFileSync(`src/types/schema/${name}.schema.json`, "utf8"));
  stripFieldTitles(schema);
  const ts = await compile(schema, name, { bannerComment: "", additionalProperties: false });
  out += ts.trim() + "\n\n";
}
writeFileSync("src/types/generated.ts", out.trimEnd() + "\n");
console.log("wrote src/types/generated.ts");
